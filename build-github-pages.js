const fs = require("node:fs");
const path = require("node:path");

const root = __dirname;
const docs = path.join(root, "docs");
const apiBase = (process.env.GITHUB_PAGES_API_BASE || "https://emmanuel-transit-pulse.emmanuelkuh966.chatgpt.site").replace(/\/+$/, "");

let html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const appScriptPattern = /  <script>\r?\n    const app = \{/;

if (!appScriptPattern.test(html)) {
  throw new Error("Could not find application script block.");
}

html = html.replace(
  appScriptPattern,
  `  <script>\n    window.TRANSIT_API_BASE = ${JSON.stringify(apiBase)};\n  </script>\n  <script>\n    const app = {`
);

fs.rmSync(docs, { recursive: true, force: true });
fs.mkdirSync(docs, { recursive: true });
fs.writeFileSync(path.join(docs, "index.html"), html);
fs.writeFileSync(path.join(docs, ".nojekyll"), "");
fs.writeFileSync(
  path.join(docs, "README.md"),
  `# Transit Intelligence GitHub Pages Build\n\nThis folder is generated by \`node build-github-pages.js\`.\n\nIt hosts the static front-end for GitHub Pages and points API calls to:\n\n\`${apiBase}\`\n\nGitHub Pages cannot run the Node API server or store private transit API keys. Keep realtime data on the Node/Sites API server and publish this folder as the Pages front-end.\n`
);

console.log(`Built docs/ for GitHub Pages using API base ${apiBase}`);
